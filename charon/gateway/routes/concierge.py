@router.post("/evaluate")
async def evaluate_task(payload: EvaluateTaskRequest, request: Request):
    """Evaluate completed action and generate next-step proposal if applicable."""
    concierge = getattr(request.app.state, "concierge", None)
    if not concierge:
        raise HTTPException(status_code=503, detail="Concierge Service is not initialized on daemon.")

    try:
        proposal = await concierge.get_next_step(
            user_query=payload.user_query,
            completed_action=payload.completed_action,
            execution_result=payload.execution_result,
            blackboard_artifacts=payload.blackboard_artifacts or "",
        )
        if not proposal:
            return {"has_proposal": False, "proposal": None}

        return {
            "has_proposal": True,
            "proposal": proposal.model_dump() if hasattr(proposal, "model_dump") else proposal.dict(),
        }
    except Exception as exc:
        logger.error(f"[ConciergeRoute] Error evaluating task: {exc}")
        raise HTTPException(status_code=500, detail=str(exc))


