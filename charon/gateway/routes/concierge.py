@router.post("/registry/reload")
async def reload_registry(request: Request):
    """Reload central JSON registry options into active Concierge Service instance."""
    concierge = getattr(request.app.state, "concierge", None)
    if not concierge:
        raise HTTPException(status_code=503, detail="Concierge Service is not initialized on daemon.")

    concierge.reload_registry()
    return {"status": "ok", "message": "Concierge configuration reloaded from registry."}