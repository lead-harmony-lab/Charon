@router.post("/speech/synthesize")
async def synthesize_speech(payload: SpeechSynthesizeRequest):
    """
    Converts text to audio stream (TTS) accompanied by timed viseme mouth-shape cues
    for real-time desktop HUD lip-syncing.
    """
    try:
        result = await speech_engine.synthesize_speech(
            text=payload.text,
            voice_id=payload.voice_id,
            speed=payload.speed or 1.0,
        )
        return result
    except Exception as exc:
        logger.error(f"[ConciergeRoute] Error during speech synthesis: {exc}")
        raise HTTPException(status_code=500, detail=str(exc))


@router.post("/speech/transcribe")
async def transcribe_speech(
    file: UploadFile = File(...),
    language: Optional[str] = "en"
):
    """
    Ingests raw audio buffers (WAV / OGG / MP3) for local STT transcription.
    """
    try:
        audio_bytes = await file.read()
        result = await speech_engine.transcribe_audio(
            audio_bytes=audio_bytes,
            content_type=file.content_type or "audio/wav",
            language=language or "en",
        )
        return result
    except Exception as exc:
        logger.error(f"[ConciergeRoute] Error during speech transcription: {exc}")
        raise HTTPException(status_code=500, detail=str(exc))


