@router.post("/context/window")
async def ingest_window_context(payload: WindowContextRequest, request: Request):
    """Ingests desktop window focus events (GNOME Shell extension / window manager)."""
    concierge = getattr(request.app.state, "concierge", None)
    if not concierge:
        raise HTTPException(status_code=503, detail="Concierge Service is not initialized on daemon.")

    try:
        if hasattr(concierge.sensor, "log_window_context"):
            concierge.sensor.log_window_context(
                app_name=payload.app_name,
                window_title=payload.window_title,
                active_file_path=payload.active_file_path,
                pid=payload.pid,
            )
        return {"status": "success", "ingested": "window_focus", "app": payload.app_name}
    except Exception as exc:
        logger.error(f"[ConciergeRoute] Error ingesting window context: {exc}")
        raise HTTPException(status_code=500, detail=str(exc))


